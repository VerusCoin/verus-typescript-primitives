import { createRequire } from 'module';
import * as primitives from '../../index';
import { DATA_TYPE_DATAHASH, DATA_TYPE_VDXFDATA } from '../../constants/pbaas';

const fixture = require('../fixtures/mmr/daemon-rpc.json').requestBoundaries;
const { requestBoundaryCases, captureRequestBoundaries, cliRequest } =
  createRequire(__filename)('../../../scripts/fixtures/mmr-request-boundaries');
const hashTypes = { sha256: 5, sha256D: 4, blake2b: 1 };

describe('captured unsigned daemon MMR request boundaries', () => {
  test.each([
    ['hex-valid', -3, /Supported request/],
    ['hex-valid', -8, /Supported request/],
    ['hex-empty', -28, /Unexpected RPC error/],
    ['hex-empty', -32603, /Unexpected RPC error/],
  ])(
    'aborts capture for %s with unexpected error %s',
    async (name, code, expectedError) => {
      let currentName: string;
      const rpc = async () => {
        if (currentName === name) {
          throw new Error(
            `signdata: ${JSON.stringify({ code, message: 'Injected failure' })}`
          );
        }
        return { mmrdescriptor: {} };
      };

      await expect(
        captureRequestBoundaries(primitives, rpc, {
          onRequest: (item: any) => {
            currentName = item.name;
          },
        })
      ).rejects.toThrow(expectedError);
    }
  );

  test('retains the complete reproducible request matrix', () => {
    const expected = requestBoundaryCases(primitives);
    const recorded = fixture.cases.map(({ daemon, ...item }: any) => item);
    const byName = (left: any, right: any) =>
      left.name.localeCompare(right.name);

    expect(recorded.sort(byName)).toEqual(expected.sort(byName));
    expect(new Set(expected.map((item: any) => item.name)).size).toBe(
      expected.length
    );
    expect(fixture.scopeNotes.join(' ')).toContain(
      'no RPC wire representation'
    );
  });

  test.each(fixture.cases.map((item: any) => [item.name, item]))(
    'preserves the local lossless conversion policy: %s',
    (_name: string, item: any) => {
      const convert = () =>
        primitives.PartialMMRData.fromCLIJson(
          cliRequest(item.request)
        ).toCLIJson();

      if (item.localPolicy === 'reject') {
        expect(convert).toThrow();
      } else {
        expect(convert).not.toThrow();
      }

      if (item.daemon.status === 'error') {
        expect([-3, -8]).toContain(item.daemon.code);
        expect(item.daemon.message).not.toEqual('');
        expect(item.localPolicy).not.toBe('supported');
      } else {
        expect(item.daemon.status).toBe('success');
        expect(item.daemon.mmrdescriptor.version).toBe(1);
      }
    }
  );

  test.each(
    fixture.cases
      .filter((item: any) => item.localPolicy === 'supported')
      .map((item: any) => [item.name, item])
  )(
    'matches independently captured leaf and root bytes: %s',
    (_name: string, item: any) => {
      const parsed = primitives.PartialMMRData.fromCLIJson(
        cliRequest(item.request)
      );
      const objectHashType = hashTypes[item.request.hashtype || 'sha256'];
      const mmrHashType =
        parsed.data.length === 1
          ? objectHashType
          : hashTypes[item.request.mmrhashtype || 'blake2b'];
      const descriptor = primitives.MMRDescriptor.fromDaemonJson(
        item.daemon.mmrdescriptor
      );
      const hashes = parsed.data.map((unit, index) => {
        if (unit.type.eq(DATA_TYPE_DATAHASH)) {
          const bytes = Buffer.from(unit.data as Buffer);
          return objectHashType === 5 ? bytes : bytes.reverse();
        }

        const payload = unit.type.eq(DATA_TYPE_VDXFDATA)
          ? (unit.data as primitives.VdxfUniValue).toBuffer()
          : (unit.data as Buffer);
        // A missing/null request salt is generated by the daemon. Use that
        // captured salt, rather than the captured hash, to recompute the root.
        const salt = parsed.salt
          ? parsed.salt[index]
          : descriptor.dataDescriptors[index].salt;
        expect(salt).toHaveLength(32);
        return primitives.hashData(
          Buffer.concat([payload, salt]),
          objectHashType
        );
      });

      expect(descriptor.objectHashType).toBe(objectHashType);
      expect(descriptor.mmrHashType).toBe(mmrHashType);
      expect(descriptor.mmrHashes.decodeHashVector(true)).toEqual(hashes);
      expect(descriptor.mmrRoot.objectdata).toEqual(
        primitives.getMMRRoot(hashes, mmrHashType)
      );
    }
  );

  test.each(['omitted', 'null'])(
    'captures default salts for ordinary and hash-only leaves: %s',
    (mode) => {
      const ordinary = fixture.cases.find(
        (item: any) => item.name === `default-salt/${mode}/message`
      );
      const hashOnly = fixture.cases.find(
        (item: any) => item.name === `default-salt/${mode}/datahash`
      );
      for (const item of [ordinary, hashOnly]) {
        expect(item.request.mmrsalt).toBe(mode === 'null' ? null : undefined);
        expect(
          primitives.PartialMMRData.fromCLIJson(cliRequest(item.request)).salt
        ).toBeUndefined();
      }

      const messageLeaf = primitives.DataDescriptor.fromDaemonJson(
        ordinary.daemon.mmrdescriptor.datadescriptors[0]
      );
      expect(messageLeaf.objectdata).toEqual(Buffer.from('abc'));
      expect(messageLeaf.salt).toHaveLength(32);

      const hashLeaf = primitives.DataDescriptor.fromDaemonJson(
        hashOnly.daemon.mmrdescriptor.datadescriptors[0]
      );
      expect(hashLeaf.objectdata).toHaveLength(0);
      expect(hashLeaf.salt).toBeUndefined();
    }
  );

  test.each(
    fixture.cases
      .filter((item: any) => item.sameOutcomeAs)
      .map((item: any) => [item.name, item])
  )(
    'captures fixed precedence and ignored prior data: %s',
    (_name: string, item: any) => {
      const control = fixture.cases.find(
        (candidate: any) => candidate.name === item.sameOutcomeAs
      );
      expect(item.daemon.status).toBe(control.daemon.status);

      if (item.daemon.status === 'success') {
        expect(item.daemon.mmrdescriptor.mmrroot).toEqual(
          control.daemon.mmrdescriptor.mmrroot
        );
      } else {
        expect(item.daemon).toEqual(control.daemon);
      }
    }
  );

  test('covers every pair of recognized keys in both insertion orders', () => {
    const cases = fixture.cases.filter((item: any) =>
      /^precedence-.*-(forward|reverse)$/.test(item.name)
    );
    expect(cases).toHaveLength(30);

    for (const item of cases) {
      expect(Object.keys(item.request.mmrdata[0])).toHaveLength(2);
      expect(item.localPolicy).toBe('reject');
    }
  });
});
